const catalogs: TranslationCatalog = { en, zh, ja };

/** Get current locale from the persisted language atom. */
export function getLocale(): string {
  // Read synchronously from localStorage since this may be called outside React
  if (typeof window !== 'undefined') {
    try {
      const stored = localStorage.getItem('hermes-language');
      if (stored) return stored.replace(/^"|"$/g, '');
    } catch {}
  }
  return 'en';
}

/** Look up a translation key in the current locale. */
export function t(key: string): string {
  const locale = getLocale();
  return catalogs[locale]?.[key] ?? catalogs.en?.[key] ?? key;
}

/**
 * React hook that returns the `t` function and re-renders when locale changes.
 * Use this in components that need to display translated text.
 */
export function useTranslation() {
  const locale = useAtomValue(languageAtom);
  // Depend on locale so React re-renders when language changes
  const localeKey = locale;

  const translate = useCallback(
    (key: string): string => {
      return catalogs[localeKey]?.[key] ?? catalogs.en?.[key] ?? key;
    },
    [localeKey],
  );

  return { t: translate, locale };
}

export const i18n = { t, getLocale };
